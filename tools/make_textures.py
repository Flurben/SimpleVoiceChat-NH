def mask(text):
    rows = [r for r in text.strip("\n").split("\n")]
    assert len(rows) == 16, len(rows)
    for r in rows:
        assert len(r) == 16, (len(r), r)
    return [[c == "#" for c in r] for r in rows]


def draw_mask(img, m, color, ox=0, oy=0, outline=None):
    px = img.load()
    if outline is not None:
        for y in range(16):
            for x in range(16):
                if m[y][x]:
                    continue
                near = False
                for dy in (-1, 0, 1):
                    for dx in (-1, 0, 1):
                        yy, xx = y + dy, x + dx
                        if 0 <= yy < 16 and 0 <= xx < 16 and m[yy][xx]:
                            near = True
                if near:
                    px[ox + x, oy + y] = outline
    for y in range(16):
        for x in range(16):
            if m[y][x]:
                px[ox + x, oy + y] = color


def slash(img, ox, oy, forced=False):
    d = ImageDraw.Draw(img)
    if forced:
        d.ellipse((ox + 0.5, oy + 0.5, ox + 15.5, oy + 15.5), outline=BLACK, width=3)
        d.ellipse((ox + 1.5, oy + 1.5, ox + 14.5, oy + 14.5), outline=RED, width=1)
    d.line((ox + 13, oy + 2, ox + 2, oy + 13), fill=BLACK, width=4)
    d.line((ox + 13, oy + 2, ox + 2, oy + 13), fill=RED, width=2)


def head(img, ox, oy, hair, skin, eyes):
    """A 6x6 pixel face with a 1 px border."""
    px = img.load()
    for y in range(8):
        for x in range(8):
            px[ox + x, oy + y] = BLACK
    for y in range(6):
        for x in range(6):
            c = skin
            if y < 2 or (y == 2 and x in (0, 5)):
                c = hair
            if y == 3 and x in (1, 4):
                c = eyes
            if y == 5 and 2 <= x <= 3:
                c = (130, 80, 60, 255)
            px[ox + 1 + x, oy + 1 + y] = c


def cell(atlas, index):
    return (index % 16) * 16, (index // 16) * 16


def build():
    atlas = Image.new("RGBA", (256, 256), (0, 0, 0, 0))
    mic, spk, spk_small = mask(MIC), mask(SPEAKER), mask(SPEAKER_SMALL)

    def put(index, m, color, outline=None, slashed=0):
        x, y = cell(atlas, index)
        draw_mask(atlas, m, color, x, y, outline)
        if slashed:
            slash(atlas, x, y, forced=slashed == 2)

    # HUD and name tag icons: white with a black outline
    put(0, mic, WHITE, BLACK)                 # microphone
    put(1, mic, WHITE, BLACK, 1)              # microphone off
    put(2, mic, GRAY, BLACK)                  # microphone whisper
    put(3, mic, WHITE, BLACK, 2)              # microphone forced off
    put(4, spk, WHITE, BLACK)                 # speaker
    put(5, spk, WHITE, BLACK, 1)              # speaker off
    put(6, spk_small, GRAY, BLACK)            # speaker whisper
    put(7, spk, WHITE, BLACK, 2)              # speaker forced off
    put(8, mask(PLUG), WHITE, BLACK, 1)       # disconnected
    put(9, mask(LOCK), WHITE, BLACK)          # lock on dark backgrounds

    # Button icons: dark
    put(16, mic, DARK)                        # mic button
    put(17, mic, DARK, None, 1)               # mic button muted
    put(18, spk, DARK)                        # speaker button
    put(19, spk, DARK, None, 1)               # speaker button disabled
    put(20, mask(EYE), DARK)                  # hide icons button (visible)
    put(21, mask(EYE), DARK, None, 1)         # hide icons button (hidden)
    put(22, mask(CIRCLE), (70, 70, 80, 255))  # record off
    put(23, mask(CIRCLE), RED, DARKRED)       # record on
    put(24, mask(SLIDERS), DARK)              # adjust volumes
    put(25, mask(LOCK), DARK)                 # lock
    put(26, mask(CHECK), GREEN, DARKGREEN)    # device selected
    put(27, spk, DARK)                        # test speaker
    put(28, spk_small, DARK)                  # other volume
    put(29, mic, DARK, None, 2)               # mic button forced off
    put(30, spk, DARK, None, 2)               # speaker button forced off

    # Leave: a door with a red arrow
    x, y = cell(atlas, 32)
    draw_mask(atlas, mask(LEAVE_DOOR), DARK, x, y)
    draw_mask(atlas, mask(ARROW), RED, x, y)

    # Group: two heads
    x, y = cell(atlas, 33)
    head(atlas, x + 1, y + 2, (90, 60, 30, 255), (220, 170, 130, 255), (60, 60, 160, 255))
    head(atlas, x + 7, y + 7, (230, 200, 80, 255), (240, 190, 150, 255), (40, 120, 40, 255))

    # Group HUD button, shown and hidden
    for i, off in ((34, False), (35, True)):
        x, y = cell(atlas, i)
        head(atlas, x + 1, y + 1, (90, 60, 30, 255), (220, 170, 130, 255), (60, 60, 160, 255))
        head(atlas, x + 1, y + 8, (230, 200, 80, 255), (240, 190, 150, 255), (40, 120, 40, 255))
        head(atlas, x + 8, y + 4, (40, 40, 40, 255), (200, 150, 110, 255), (120, 60, 20, 255))
        if off:
            slash(atlas, x, y)

    # Invite: head with a green plus
    x, y = cell(atlas, 36)
    head(atlas, x + 2, y + 3, (90, 60, 30, 255), (220, 170, 130, 255), (60, 60, 160, 255))
    d = ImageDraw.Draw(atlas)
    d.rectangle((x + 11, y + 8, x + 13, y + 14), fill=DARKGREEN)
    d.rectangle((x + 9, y + 10, x + 15, y + 12), fill=DARKGREEN)
    d.line((x + 12, y + 9, x + 12, y + 13), fill=GREEN)
    d.line((x + 10, y + 11, x + 14, y + 11), fill=GREEN)

    atlas.save(OUT + "gui/icons.png")

    # Mod logo: the microphone on a rounded badge
    logo = Image.new("RGBA", (128, 128), (0, 0, 0, 0))
    d = ImageDraw.Draw(logo)
    d.rounded_rectangle((4, 4, 123, 123), radius=24, fill=(30, 110, 70, 255), outline=(10, 50, 30, 255), width=4)
    d.rounded_rectangle((12, 12, 115, 60), radius=18, fill=(45, 140, 90, 255))
    icon = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    draw_mask(icon, mic, WHITE, 0, 0, BLACK)
    big = icon.resize((96, 96), Image.NEAREST)
    logo.alpha_composite(big, (16, 18))
    logo.save(OUT + "../logo.png")

    preview = atlas.crop((0, 0, 256, 48)).resize((1024, 192), Image.NEAREST)
    bg = Image.new("RGBA", preview.size, (120, 120, 120, 255))
    bg.alpha_composite(preview)
    return bg


